#!/usr/bin/env node
// Generates a kit's object-model typings and descriptor for @kition/script from its KDM schema
// (`model/schema.json` in the kit's repository) and its command catalogue (captured from the
// kit's package, the engine loaded in Node).
//
//   node packages/script/scripts/generate-kit.mjs --schema <schema.json> --package <kit-ui dir> \
//     --name Slide --out packages/script/kits/slide.ts
//
// The output is checked in; regenerate it when the kit's schema or commands change.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { pathToFileURL } from 'node:url'
import { parseArgs } from 'node:util'

const { values: args } = parseArgs({
  options: { schema: { type: 'string' }, package: { type: 'string' }, name: { type: 'string' }, out: { type: 'string' } },
})
if (!args.schema || !args.name) {
  console.error('usage: generate-kit.mjs --schema <schema.json> [--package <kit-ui dir>] --name <Name> [--out <file.ts>]')
  process.exit(2)
}

const schema = JSON.parse(readFileSync(args.schema, 'utf8'))
const commands = args.package ? await capture(args.package) : []

/** The kit's command catalogue, from its engine in Node. */
async function capture(dir) {
  const engineDir = join(dir, 'engine')
  const files = readdirSync(engineDir)
  const script = files.find((name) => name.endsWith('.js'))
  const wasm = files.find((name) => name.endsWith('_bg.wasm'))
  const module = await import(pathToFileURL(join(engineDir, script)).href)
  // A wasm-pack module takes its WebAssembly; a TypeScript engine (ts-worker) prepares itself.
  if (typeof module.initSync === 'function') module.initSync({ module: readFileSync(join(engineDir, wasm)) })
  else await module.default({ base: pathToFileURL(engineDir + '/').href, read: async (name) => new Uint8Array(readFileSync(join(engineDir, name))) })
  const engine = Object.values(module).find((value) => typeof value === 'function' && typeof value.create === 'function' && 'commands' in (value.prototype ?? {}))
  const document = engine.create('untitled', 960, 540)
  const catalogue = JSON.parse(document.commands())
  document.free?.()
  return catalogue
}

/** Plain ASCII for comments: no comment terminators, no typographic characters. */
const ascii = (text) =>
  String(text)
    .replaceAll('*/', '* /')
    .replaceAll('…', '...')
    .replace(/[^\x20-\x7e]/g, '?')

const key = (name) => (/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) ? name : JSON.stringify(name))

/** A KDM register field's TypeScript type. */
function registerType(field) {
  const base = {
    string: 'string',
    number: 'number',
    integer: 'number',
    boolean: 'boolean',
    json: 'Json',
    blob: 'BlobRef',
    ref: 'string',
  }[field.kind]
  const type = field.kind === 'enum' ? field.values.map((value) => JSON.stringify(value)).join(' | ') : base
  return field.optional ? `${type} | null` : type
}

/** `ModelObject`'s own members: a schema field with one of these names is not a property of the proxy. */
const OBJECT_MEMBERS = new Set(['id', 'type', 'load', 'delete', 'isLoaded', 'toJSON'])

const lines = []
const emit = (line = '') => lines.push(line)
const kitConst = `${args.name.charAt(0).toLowerCase()}${args.name.slice(1)}Kit`

emit(`// Generated by packages/script/scripts/generate-kit.mjs from ${schema.kit}'s model/schema.json (schema version`)
emit(`// ${schema.schemaVersion})${commands.length ? ' and its command catalogue' : ''}. Do not edit; regenerate it.`)
emit(`import type { CommandMap, ModelDocument, ModelList, ModelMap, ModelObject, ModelText, ModelTree, RequestContext } from '../src/index'`)
emit(`import { registerKit, type KitDescriptor } from '../src/kits'`)
emit()
emit(`type Json = null | boolean | number | string | Json[] | { [key: string]: Json }`)
emit(`type BlobRef = { hash: string; mime: string; size: number }`)
emit()
emit(`/** ${schema.kit}: registered with @kition/script when this module loads. */`)
emit(`export const ${kitConst}: KitDescriptor = registerKit({ id: ${JSON.stringify(schema.kit)}, schema: ${JSON.stringify(schema)} })`)

for (const [type, def] of Object.entries(schema.types)) {
  emit()
  emit(`/** The fields a new \`${type}\` takes (\`list.add(fields)\`). */`)
  emit(`export type ${type}Fields = {`)
  for (const [name, field] of Object.entries(def.fields)) {
    // A read-only field (rule OM8) is the kit's to write: a new object does not take it.
    if (['text', 'list', 'tree', 'map'].includes(field.kind) || field.readOnly) continue
    const optional = field.optional ? '?' : ''
    const type = field.kind === 'ref' ? `string | ModelObject${field.optional ? ' | null' : ''}` : registerType(field)
    emit(`  ${key(name)}${optional}: ${type}`)
  }
  emit(`}`)
  emit()
  const kept = def.readOnly
    ? ' Read-only: the kit keeps it as it is (rule OM8); scripts read it and run commands.'
    : def.readOnlyWhen
      ? ` Read-only when \`${def.readOnlyWhen.field}\` is ${def.readOnlyWhen.values.map((value) => JSON.stringify(value)).join(' or ')} (rule OM8).`
      : ''
  emit(`/** A \`${type}\` of ${schema.kit}.${kept} */`)
  emit(`export interface ${type} extends ModelObject {`)
  for (const [name, field] of Object.entries(def.fields)) {
    if (OBJECT_MEMBERS.has(name)) {
      emit(`  // The field \`${name}\` (${field.kind}) is not a property: \`${name}\` is the proxy's own. Read it with toJSON() after load().`)
      continue
    }
    if (field.readOnly) {
      // Content the kit keeps verbatim (rule OM8): read, never written through the object model.
      emit(`  /** Read-only: the kit keeps it as it is. */`)
      const read = { list: `ModelList<${field.of}, ${field.of}Fields>`, map: 'ModelMap<Json>', tree: `ModelTree<${field.of}, ${field.of}Fields>`, text: 'ModelText' }[field.kind]
      emit(`  readonly ${key(name)}: ${read ?? registerType(field)}`)
      continue
    }
    switch (field.kind) {
      case 'list':
        emit(`  readonly ${key(name)}: ModelList<${field.of}, ${field.of}Fields>`)
        break
      case 'map':
        emit(`  readonly ${key(name)}: ModelMap<Json>`)
        break
      case 'tree':
        emit(`  readonly ${key(name)}: ModelTree<${field.of}, ${field.of}Fields>`)
        break
      case 'text':
        emit(`  get ${key(name)}(): ModelText`)
        emit(`  set ${key(name)}(value: string)`)
        break
      case 'ref':
        emit(`  /** The id of a \`${field.of}\`. */`)
        emit(`  get ${key(name)}(): ${registerType(field)}`)
        emit(`  set ${key(name)}(value: ${field.of} | string${field.optional ? ' | null' : ''})`)
        break
      default:
        emit(`  ${key(name)}: ${registerType(field)}`)
    }
  }
  emit(`}`)
}

/** A DeepSeek Harness value spec as a TypeScript type. */
function valueType(spec) {
  if (!spec || typeof spec !== 'object') return 'Json'
  if (Array.isArray(spec.enum) && spec.enum.length) return spec.enum.map((value) => JSON.stringify(value)).join(' | ')
  switch (spec.type) {
    case 'string':
      return 'string'
    case 'integer':
    case 'number':
      return 'number'
    case 'boolean':
      return 'boolean'
    case 'array':
      return `Array<${valueType(spec.items)}>`
    case 'object': {
      if (!spec.properties) return '{ [key: string]: Json }'
      const required = new Set(Object.entries(spec.properties).filter(([, inner]) => inner?.required === true).map(([name]) => name))
      const fields = Object.entries(spec.properties).map(([name, inner]) => `${key(name)}${required.has(name) ? '' : '?'}: ${valueType(inner)}`)
      return `{ ${fields.join('; ')} }`
    }
    default:
      return 'Json'
  }
}

// A schema type named `Record` (kit.table) shadows TypeScript's own in this module.
const noParams = Object.hasOwn(schema.types, 'Record') ? '{ [key: string]: never }' : 'Record<string, never>'

if (commands.length) {
  emit()
  emit(`/** Every command of ${schema.kit}, by id, with its parameters. */`)
  emit(`export interface ${args.name}Commands extends CommandMap {`)
  for (const command of commands) {
    // What the command acts on (`targets`, the parameter a run step's `on` fills) and the editor
    // state it reads besides its parameters (`reads`), as the engine declares them.
    const acts = command.targets ? `Acts on \`${command.targets}\`` : null
    const reads = command.reads?.length ? `Reads the ${command.reads.join(', ')}` : null
    const notes = [command.title, command.description, command.params && `Params: ${command.params}`, acts, reads, command.mutates ? 'Changes the document' : null]
      .filter(Boolean)
      .map((note) => note.replace(/\.$/, ''))
    emit(`  /** ${ascii(`${notes.join('. ')}.`)} */`)
    const properties = command.schema && typeof command.schema === 'object' ? Object.entries(command.schema) : []
    if (properties.length === 0) {
      emit(`  ${JSON.stringify(command.id)}: ${noParams}`)
      continue
    }
    const fields = properties.map(([name, spec]) => {
      const doc = spec?.description ? `/** ${ascii(spec.description)} */ ` : ''
      return `${doc}${key(name)}${spec?.required === true ? '' : '?'}: ${valueType(spec)}`
    })
    emit(`  ${JSON.stringify(command.id)}: { ${fields.join('; ')} }`)
  }
  emit(`}`)
  emit()
  emit(`/** A ${args.name} file opened with \`openDocument<${schema.root}, ${args.name}Commands>\`. */`)
  emit(`export type ${args.name}Document = ModelDocument<${schema.root}, ${args.name}Commands>`)
  emit(`export type ${args.name}Context = RequestContext<${schema.root}, ${args.name}Commands>`)
}

const text = `${lines.join('\n')}\n`
if (args.out) writeFileSync(args.out, text)
else process.stdout.write(text)
