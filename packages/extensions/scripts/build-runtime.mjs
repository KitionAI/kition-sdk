#!/usr/bin/env node
// Builds what an extension sandbox runs, as checked-in files a host can carry without a bundler
// step of its own:
//
//   sandbox/sandbox.html      the sandbox page: sandbox/bootstrap.js inline, allowed by its hash
//   sandbox/panel.html        the panel page: src/runtime/panel.ts built inline, allowed by its hash
//   src/generated/runtime.ts  WORKER_RUNTIME (the worker, one classic script), SANDBOX_HTML, and
//                             PANEL_HTML
//
//   node packages/extensions/scripts/build-runtime.mjs          write them
//   node packages/extensions/scripts/build-runtime.mjs --check  fail when they are stale
//
// The generated module records a hash of its inputs (runtimeInputs below); a test fails when they
// change without a rebuild.
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'
import { inputsHash } from './runtime-inputs.mjs'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const check = process.argv.includes('--check')

const generatedPath = join(root, 'src/generated/runtime.ts')
const htmlPath = join(root, 'sandbox/sandbox.html')
const panelPath = join(root, 'sandbox/panel.html')

if (check) {
  const current = readFileSync(generatedPath, 'utf8')
  if (!current.includes(`RUNTIME_INPUTS_SHA256 = '${inputsHash()}'`)) {
    console.error(`FAIL ${relative(process.cwd(), generatedPath)} is stale; run node packages/extensions/scripts/build-runtime.mjs`)
    process.exit(1)
  }
  console.log('PASS the extension runtime is current')
  process.exit(0)
}

const { build } = await import('vite')
/** `entry` as one classic script. */
async function bundle(entry, name) {
  const output = await build({
    configFile: false,
    logLevel: 'warn',
    root,
    build: {
      write: false,
      minify: false,
      target: 'es2022',
      lib: { entry: join(root, entry), formats: ['iife'], name, fileName: () => 'bundle.js' },
      rollupOptions: { output: { inlineDynamicImports: true } },
    },
  })
  const chunks = (Array.isArray(output) ? output : [output]).flatMap((result) => result.output)
  const chunk = chunks.find((item) => item.type === 'chunk')
  if (!chunk) throw new Error(`vite built nothing from ${entry}`)
  return chunk.code.trim() + '\n'
}
const runtime = await bundle('src/runtime/worker.ts', 'KitionExtensionRuntime')
const panelScript = await bundle('src/runtime/panel.ts', 'KitionExtensionPanel')

const bootstrap = readFileSync(join(root, 'sandbox/bootstrap.js'), 'utf8')
const hash = createHash('sha256').update(bootstrap).digest('base64')
// No default-src: connect-src is the bootstrap's to set, per extension, before the worker starts.
const policy = [
  `script-src 'sha256-${hash}' blob:`,
  'worker-src blob:',
  "object-src 'none'",
  "base-uri 'none'",
  "form-action 'none'",
  "frame-src 'none'",
  "img-src 'none'",
  "media-src 'none'",
  "font-src 'none'",
  "style-src 'none'",
  "manifest-src 'none'",
].join('; ')
const html = `<!doctype html>
<!-- Generated by packages/extensions/scripts/build-runtime.mjs from sandbox/bootstrap.js. Do not edit; rebuild it. -->
<html lang="en">
<head>
<meta charset="utf-8">
<meta http-equiv="Content-Security-Policy" content="${policy}">
<meta name="referrer" content="no-referrer">
<title>Kition extension sandbox</title>
<script>${bootstrap}</script>
</head>
<body></body>
</html>
`
writeFileSync(htmlPath, html)

// The panel page: no default-src either, for the same reason. Scripts: its own (by hash) and the
// blob scripts it makes of the panel's inline scripts; inline styles; images and fonts only from
// data: and blob: URLs, so nothing reaches the network but connect-src.
const panelHash = createHash('sha256').update(panelScript).digest('base64')
const panelPolicy = [
  `script-src 'sha256-${panelHash}' blob:`,
  "style-src 'unsafe-inline'",
  'img-src data: blob:',
  'font-src data:',
  'media-src data: blob:',
  "worker-src 'none'",
  "object-src 'none'",
  "base-uri 'none'",
  "form-action 'none'",
  "frame-src 'none'",
  "manifest-src 'none'",
].join('; ')
const panelHtml = `<!doctype html>
<!-- Generated by packages/extensions/scripts/build-runtime.mjs from src/runtime/panel.ts. Do not edit; rebuild it. -->
<html lang="en">
<head>
<meta charset="utf-8">
<meta http-equiv="Content-Security-Policy" content="${panelPolicy}">
<meta name="referrer" content="no-referrer">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Kition extension panel</title>
<style>html{color-scheme:light;font-family:var(--kit-font-sans,system-ui,sans-serif);font-size:14px;color:var(--kit-text,#1a1a1a);background:var(--kit-surface,#fff)}body{margin:0}</style>
<script>${panelScript}</script>
</head>
<body></body>
</html>
`
writeFileSync(panelPath, panelHtml)

writeFileSync(
  generatedPath,
  `// Generated by packages/extensions/scripts/build-runtime.mjs. Do not edit; rebuild it.
/* eslint-disable */

/** A hash of the sources this module was built from (scripts/runtime-inputs.mjs). */
export const RUNTIME_INPUTS_SHA256 = '${inputsHash()}'

/** The sandbox worker: one classic script (src/runtime/worker.ts and what it imports). */
export const WORKER_RUNTIME: string = ${JSON.stringify(runtime)}

/** The sandbox page (sandbox/sandbox.html), for hosts that serve it from memory. */
export const SANDBOX_HTML: string = ${JSON.stringify(html)}

/** The panel page (sandbox/panel.html), for hosts that serve it from memory. */
export const PANEL_HTML: string = ${JSON.stringify(panelHtml)}
`,
)
console.log(`wrote ${relative(process.cwd(), htmlPath)}, ${relative(process.cwd(), panelPath)}, and ${relative(process.cwd(), generatedPath)} (worker ${runtime.length} bytes, panel ${panelScript.length} bytes)`)
