#!/usr/bin/env node
// deterministic agent reference from committed SDK catalogues; never loads a kit.
// Uses the docs-gen path established on the documentation branches.
// node tools/docs-gen/build.mjs [--dir packages/script/kits] [--out docs/generated] [--check]
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { parseArgs } from 'node:util'
import ts from 'typescript'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..')
const marker = 'Generated by tools/docs-gen/build.mjs. Do not edit.'
const compare = (a, b) => a < b ? -1 : a > b ? 1 : 0
const sorted = (values) => [...values].sort(compare)
const sourceOf = (kit) => `packages/script/kits/${kit}.ts`
const pageOf = (kit, id) => `kits/${kit}/commands/${encodeURIComponent(id)}.md`
const textOf = (node, source) => node.getText(source)
const commentOf = (node) => {
  const source = node.getSourceFile()
  // TypeScript leaves same-line property JSDoc unattached to the property node.
  const docs = node.jsDoc ?? (ts.getTrailingCommentRanges(source.text, node.pos) ?? [])
    .filter((range) => range.end <= node.getStart(source))
    .map((range) => ts.parseIsolatedJSDocComment(source.text, range.pos, range.end - range.pos)?.jsDoc)
    .filter(Boolean)
  return docs.map((doc) => ts.getTextOfJSDocComment(doc.comment) ?? '').join('\n').trim()
}
const nameOf = (node) => ts.isIdentifier(node) || ts.isStringLiteral(node) || ts.isNumericLiteral(node) ? node.text : null
const codeBlock = (text, language) => {
  const ticks = '`'.repeat(Math.max(3, ...[...text.matchAll(/`+/g)].map((match) => match[0].length + 1)))
  return `${ticks}${language}\n${text}\n${ticks}`
}
const cell = (text) => String(text).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/\|/g, '&#124;').replace(/\r?\n/g, '<br>')

/** JSON Schema for the information retained in a generated TS type. Unrepresented metadata
 * stays unknown. The original type is always retained, including nested property comments. */
export function schemaOf(node, source) {
  const original = { 'x-typescript-type': textOf(node, source) }
  let schema
  switch (node.kind) {
    case ts.SyntaxKind.StringKeyword: schema = { type: 'string' }; break
    case ts.SyntaxKind.NumberKeyword: schema = { type: 'number' }; break
    case ts.SyntaxKind.BooleanKeyword: schema = { type: 'boolean' }; break
    case ts.SyntaxKind.NeverKeyword: schema = { not: {} }; break
    default:
      if (ts.isParenthesizedTypeNode(node)) schema = schemaOf(node.type, source)
      else if (ts.isLiteralTypeNode(node)) {
        if (node.literal.kind === ts.SyntaxKind.NullKeyword) schema = { type: 'null' }
        else if (ts.isStringLiteral(node.literal)) schema = { const: node.literal.text }
        else if (ts.isNumericLiteral(node.literal) || ts.isPrefixUnaryExpression(node.literal)) schema = { const: Number(textOf(node.literal, source)) }
        else if (node.literal.kind === ts.SyntaxKind.TrueKeyword || node.literal.kind === ts.SyntaxKind.FalseKeyword) schema = { const: node.literal.kind === ts.SyntaxKind.TrueKeyword }
      } else if (ts.isUnionTypeNode(node)) schema = { anyOf: node.types.map((type) => schemaOf(type, source)) }
      else if (ts.isArrayTypeNode(node)) schema = { type: 'array', items: schemaOf(node.elementType, source) }
      else if (ts.isTupleTypeNode(node)) schema = { type: 'array', prefixItems: node.elements.map((type) => schemaOf(type, source)), minItems: node.elements.length, maxItems: node.elements.length }
      else if (ts.isTypeReferenceNode(node)) {
        const name = textOf(node.typeName, source)
        if (name === 'Array' && node.typeArguments?.length === 1) schema = { type: 'array', items: schemaOf(node.typeArguments[0], source) }
        // generate-kit.mjs uses this spelling only for commands with no parameters.
        else if (name === 'Record' && node.typeArguments?.length === 2 && node.typeArguments[1].kind === ts.SyntaxKind.NeverKeyword) schema = { type: 'object', properties: {}, required: [], additionalProperties: false }
      } else if (ts.isTypeLiteralNode(node)) {
        const properties = Object.create(null)
        const required = []
        let additionalProperties = false
        const members = [...node.members].sort((a, b) => compare(a.name ? nameOf(a.name) ?? '' : '', b.name ? nameOf(b.name) ?? '' : ''))
        for (const member of members) {
          if (ts.isIndexSignatureDeclaration(member) && member.type) {
            additionalProperties = member.type.kind === ts.SyntaxKind.NeverKeyword ? false : schemaOf(member.type, source)
            continue
          }
          if (!ts.isPropertySignature(member) || !member.type || nameOf(member.name) === null) throw new Error('unsupported parameter member')
          const name = nameOf(member.name)
          properties[name] = schemaOf(member.type, source)
          const description = commentOf(member)
          if (description) properties[name].description = description
          if (!member.questionToken) required.push(name)
        }
        schema = { type: 'object', properties, required, additionalProperties }
      }
  }
  // Json and any other unexpanded reference remain unconstrained, never a fabricated schema.
  return { ...(schema ?? {}), ...original }
}

/** L1–L9 are a report. A TS catalogue cannot establish runtime behaviour or passing cases. */
function lintOf(params) {
  const unknown = (reason) => ({ status: 'unknown', reason })
  let described = 0
  let properties = 0
  let jsonTypes = 0
  const visit = (schema) => {
    if (schema['x-typescript-type'] === 'Json') jsonTypes++
    for (const property of Object.values(schema.properties ?? {})) {
      properties++
      if (property.description) described++
      visit(property)
    }
    if (schema.items) visit(schema.items)
    for (const child of [...(schema.anyOf ?? []), ...(schema.prefixItems ?? [])]) visit(child)
    if (typeof schema.additionalProperties === 'object') visit(schema.additionalProperties)
  }
  visit(params)
  return {
    L1: unknown('Required flags come from TypeScript; notation agreement is not evaluated from flattened JSDoc.'),
    L2: { status: described === properties ? 'pass' : 'missing', described, properties },
    L3: unknown('Structured units are not retained; consult each parameter description.'),
    L4: unknown('Example case results are not retained; no passing examples are claimed.'),
    L5: unknown('Output schemas are not retained.'),
    L6: unknown('Unknown-parameter rejection requires a runtime check.'),
    L7: { status: jsonTypes ? 'missing' : 'pass', json_types: jsonTypes },
    L8: unknown('Command errors are not retained; null does not mean no errors.'),
    L9: unknown('Keywords are not retained.'),
  }
}

export function parseCatalogue(text, kit) {
  if (!/^[a-z][a-z0-9-]*$/.test(kit)) throw new Error('invalid kit name')
  const source = ts.createSourceFile(`${kit}.ts`, text, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS)
  if (source.parseDiagnostics.length) throw new Error(`${kit}: invalid TypeScript catalogue`)
  const interfaces = source.statements.filter((node) => ts.isInterfaceDeclaration(node) && node.name.text.endsWith('Commands') && node.heritageClauses?.some((clause) => clause.types.some((type) => textOf(type.expression, source) === 'CommandMap')))
  if (interfaces.length !== 1) throw new Error(`${kit}: expected one Commands extends CommandMap interface`)
  const seen = new Set()
  const records = interfaces[0].members.map((member) => {
    if (!ts.isPropertySignature(member) || !member.type || !ts.isStringLiteral(member.name)) throw new Error(`${kit}: unsupported command member`)
    const id = member.name.text
    if (!id || id === '.' || id === '..' || /[\x00-\x1f\x7f]/.test(id) || seen.has(id)) throw new Error(`${kit}: invalid or duplicate command id`)
    seen.add(id)
    const description = commentOf(member) || null
    const params = schemaOf(member.type, source)
    if (params.type !== 'object') throw new Error(`${kit}: ${id}: expected an object parameter type`)
    return {
      kit, id, description,
      // This exact suffix is emitted only for mutates by generate-kit.mjs.
      mutates: description?.endsWith('Changes the document.') ?? false,
      params,
      output: null, availability: null, errors: null, examples: null, see_also: null, since: null,
      source: sourceOf(kit),
      schema_source: 'typescript',
      missing: ['output', 'availability', 'errors', 'examples', 'see_also', 'since', 'keywords', 'structured_units', 'defaults', 'constraints'],
      lint: lintOf(params),
      markdown: pageOf(kit, id),
    }
  })
  if (!records.length) throw new Error(`${kit}: empty command catalogue`)
  return records.sort((a, b) => compare(a.id, b.id))
}

export function readCatalogues(dir) {
  const names = sorted(fs.readdirSync(dir).filter((name) => name.endsWith('.ts') && name !== 'index.ts'))
  if (!names.length) throw new Error('no kit catalogues found')
  return Object.fromEntries(names.map((name) => [name.slice(0, -3), fs.readFileSync(path.join(dir, name), 'utf8')]))
}

function renderPage(record) {
  const rows = Object.entries(record.params.properties ?? {}).map(([name, schema]) => `| ${cell(name)} | ${cell(schema['x-typescript-type'])} | ${record.params.required.includes(name) ? 'yes' : 'no'} | ${cell(schema.description ?? 'Missing from catalogue.')} |`)
  return [
    `# ${record.kit}: ${record.id}`, '', `<!-- ${marker} -->`, '',
    record.description ?? 'Description missing from catalogue.', '',
    `Source: \`${record.source}\`. Mutates: ${record.mutates ? 'yes' : 'no'}.`, '',
    '## Parameters', '',
    ...(rows.length ? ['| Name | TypeScript type | Required | Description |', '| --- | --- | --- | --- |', ...rows] : ['No named parameters.']), '',
    'Required flags and schemas below describe the committed TypeScript catalogue. Defaults, numeric constraints and structured units are not retained; descriptions may specify units and coordinates.', '',
    '## Parameter schema', '', codeBlock(JSON.stringify(record.params, null, 2), 'json'), '',
    '## Returns, availability and errors', '',
    'Missing from catalogue. Consult the live kit command catalogue before execution; no return value, precondition or recovery action is inferred.', '',
    '## Examples and related commands', '',
    'Missing from catalogue. No tested examples, passing case status or related commands are inferred.', '',
    '## Metadata coverage (L1–L9)', '',
    '| Rule | Status | Evidence |', '| --- | --- | --- |',
    ...Object.entries(record.lint).map(([rule, value]) => `| ${rule} | ${value.status} | ${cell(value.reason ?? JSON.stringify(value))} |`), '',
  ].join('\n')
}

/** Builds bytes in memory first, so malformed inputs cannot cause a partial write. */
export function buildOutputs(texts, guides = []) {
  const kits = sorted(Object.keys(texts))
  if (!kits.length) throw new Error('no kit catalogues found')
  const outputs = new Map()
  const all = []
  const index = ['# Kition integration reference', '', '> Command reference for AI agents, generated from the committed SDK catalogues.', '', `<!-- ${marker} -->`, '', '## Kits', '']
  for (const kit of kits) {
    const records = parseCatalogue(texts[kit], kit)
    all.push(...records)
    index.push(`- [${kit}](kits/${kit}/llms.txt): ${records.length} commands`)
    const kitIndex = [`# ${kit} commands`, '', `<!-- ${marker} -->`, '', '## Reference', '', `- [Machine-readable commands](commands.jsonl): one JSON object per command`, '', '## Commands', '']
    for (const record of records) {
      outputs.set(record.markdown, renderPage(record))
      kitIndex.push(`- [${record.id}](commands/${encodeURIComponent(record.id)}.md): ${(record.description ?? 'Description missing from catalogue.').replace(/\s+/g, ' ')}`)
    }
    outputs.set(`kits/${kit}/llms.txt`, `${kitIndex.join('\n')}\n`)
    outputs.set(`kits/${kit}/commands.jsonl`, `${records.map((record) => JSON.stringify(record)).join('\n')}\n`)
  }
  index.push('', '## Guides', '', ...guides.map((guide) => `- [${guide.title}](${guide.url})`), '', '## Data', '', '- [All commands](commands.jsonl): one JSON object per command of every kit', '')
  outputs.set('llms.txt', index.join('\n'))
  outputs.set('commands.jsonl', `${all.map((record) => JSON.stringify(record)).join('\n')}\n`)
  return new Map([...outputs].sort(([a], [b]) => compare(a, b)))
}

function readGuides() {
  const dir = path.join(root, 'docs/sdk')
  return sorted(fs.readdirSync(dir).filter((name) => name.endsWith('.md'))).map((name) => {
    const title = /^#\s+(.+)$/m.exec(fs.readFileSync(path.join(dir, name), 'utf8'))?.[1] ?? name
    return { title, url: `https://github.com/KitionAI/kition-sdk/blob/main/docs/sdk/${encodeURIComponent(name)}` }
  })
}

const managed = (file) => /^(?:llms\.txt|commands\.jsonl|kits\/[a-z][a-z0-9-]*\/(?:llms\.txt|commands\.jsonl|commands\/[^/]+\.md))$/.test(file)

/** Check and write share byte comparison, including pages of deleted commands. Other files
 * in --out are left alone. Symlinks are refused rather than followed outside --out. */
export function syncOutputs(outputs, out, check = false) {
  const existing = new Set()
  const walk = (dir, relative = '') => {
    if (!fs.existsSync(dir)) return
    if (fs.lstatSync(dir).isSymbolicLink()) throw new Error('output directory contains a symlink')
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const file = relative ? `${relative}/${entry.name}` : entry.name
      if (entry.isSymbolicLink()) throw new Error('output directory contains a symlink')
      if (entry.isDirectory()) walk(path.join(dir, entry.name), file)
      else if (managed(file)) existing.add(file)
    }
  }
  walk(out)
  const stale = sorted([...existing].filter((file) => !outputs.has(file)))
  const changed = [...outputs].filter(([file, text]) => !existing.has(file) || fs.readFileSync(path.join(out, file), 'utf8') !== text).map(([file]) => file)
  if (!check) {
    for (const file of changed) {
      const dest = path.join(out, file)
      fs.mkdirSync(path.dirname(dest), { recursive: true })
      fs.writeFileSync(dest, outputs.get(file))
    }
    for (const file of stale) fs.unlinkSync(path.join(out, file))
  }
  return sorted([...changed, ...stale])
}

export function main(argv = process.argv.slice(2)) {
  const { values } = parseArgs({ args: argv, options: {
    dir: { type: 'string', default: path.join(root, 'packages/script/kits') },
    out: { type: 'string', default: path.join(root, 'docs/generated') },
    check: { type: 'boolean', default: false },
    help: { type: 'boolean', short: 'h' },
  } })
  if (values.help) {
    console.log('node tools/docs-gen/build.mjs [--dir <catalogue directory>] [--out <output directory>] [--check]')
    return 0
  }
  const outputs = buildOutputs(readCatalogues(values.dir), readGuides())
  const differences = syncOutputs(outputs, path.resolve(values.out), values.check)
  if (values.check && differences.length) {
    console.error('docs-gen: stale outputs; run node tools/docs-gen/build.mjs with the same --dir and --out')
    for (const file of differences) console.error(`  ${file}`)
    return 1
  }
  console.log(`docs-gen: ${outputs.size} files; ${values.check ? 'up to date' : `${differences.length} changed`}`)
  return 0
}

if (process.argv[1] && fs.realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try { process.exitCode = main() }
  catch (error) { console.error(`docs-gen: ${error.message}`); process.exitCode = 1 }
}
