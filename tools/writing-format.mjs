#!/usr/bin/env node
// Writes a kit's writing-format reference (kit-requirements W1, `docs/writing-format.md`) from its
// built engine's command catalogue and the examples in its `agent/guide.md`: the run syntax, every
// command with its parameters, the value lists (themes, layouts and every other enum), the stated
// defaults, and the examples. `agent/guide.md` (AX12) stays the short guide a model reads first.
//
//   node tools/writing-format.mjs <kit repo> <engine dir> <module> <class> [--check]
//
// <engine dir> holds <module>.js and <module>_bg.wasm (a kit package's `engine/`, which names its
// version in the package's kit.json one level up). --check writes nothing and exits 1 when the file
// differs from what the engine would give.
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const code = (value) => `\`${value}\``
const article = (name) => (/^([AEIOU]|HTML)/.test(name) ? 'an' : 'a')

/** The guide's `## Example …` sections, as `{ title, body }`. */
export function guideExamples(guide) {
  const examples = []
  let current = null
  for (const line of guide.split('\n')) {
    const heading = /^##\s+(.*)$/.exec(line)
    if (heading) {
      if (current) examples.push(current)
      current = /^example\b/i.test(heading[1]) ? { title: heading[1].trim(), body: [] } : null
    } else if (current) current.body.push(line)
  }
  if (current) examples.push(current)
  return examples.map(({ title, body }) => ({ title, body: body.join('\n').trim() }))
}

function typeOf(node) {
  if (node.type === 'array' && node.items?.type) return `${node.items.type}[]`
  if (node.type) return node.type
  if (Array.isArray(node.oneOf)) return node.oneOf.map((option) => option.type ?? 'object').join(' or ')
  return 'value'
}

function describeParam(name, node) {
  const parts = [`${code(name)} ${typeOf(node)}`]
  if (node.required) parts.push('required')
  if ('default' in node) parts.push(`default ${code(JSON.stringify(node.default))}`)
  if (Array.isArray(node.enum)) parts.push(`one of ${node.enum.map((value) => code(value)).join(' | ')}`)
  if (node.description) parts.push(node.description.replace(/\s+/g, ' ').trim())
  return parts.join(', ')
}

const cell = (text) => String(text).replaceAll('|', '\\|')

/** The reference as Markdown. */
export function writingFormat({ manifest, commands, guide = '', engineVersion }) {
  const prefix = manifest.agent?.prefix ?? manifest.id.replace(/^kit\./, '')
  const lines = [
    `# ${manifest.name} writing format`,
    '',
    `<!-- Generated by kition-sdk tools/writing-format.mjs from the ${manifest.name} engine ${engineVersion} and agent/guide.md. Regenerate it; do not edit it by hand. -->`,
    '',
    `What a model or a script writes to make or change ${article(manifest.name)} ${manifest.name} document: the run syntax, every`,
    `command and its parameters, the value lists and the defaults the engine states, and worked examples.`,
    `It is made from the command catalogue of the ${manifest.name} engine ${engineVersion}. Read`,
    '[`agent/guide.md`](../agent/guide.md) first: it says how to address things, the workflow, and the',
    'pitfalls.',
    '',
    '## Syntax',
    '',
    `Changes are steps of ${code(`${prefix}_run`)}; each step is one command with its parameters as JSON:`,
    '',
    '```json',
    `${prefix}_run { "path": "<file>", "steps": [{ "command": "<command id>", "params": { … } }] }`,
    '```',
    '',
    `A run is one step in the document's history. ${code(`${prefix}_commands`)} finds commands by words; the`,
    'lists below are the whole catalogue. A parameter marked required must be given; a parameter left out',
    "takes the engine's default (listed where the engine states one). Commands marked (reads) answer",
    'without changing the document.',
    '',
  ]

  const enums = new Map()
  const defaults = []
  for (const command of commands) {
    for (const [name, node] of Object.entries(command.schema ?? {})) {
      if (!node) continue
      if (Array.isArray(node.enum)) {
        const key = `${name}\u0000${JSON.stringify(node.enum)}`
        const entry = enums.get(key) ?? { name, values: node.enum, commands: [] }
        entry.commands.push(command.id)
        enums.set(key, entry)
      }
      if ('default' in node) defaults.push({ command: command.id, name, value: node.default })
    }
  }

  lines.push('## Value lists', '')
  if (enums.size) {
    lines.push('Themes, layouts and every other parameter that takes one of a fixed list of values.', '')
    lines.push('| Parameter | Values | Commands |', '|---|---|---|')
    const sorted = [...enums.values()].sort((a, b) => a.name.localeCompare(b.name) || a.commands[0].localeCompare(b.commands[0]))
    for (const entry of sorted) {
      lines.push(`| ${code(entry.name)} | ${cell(entry.values.map((value) => code(value)).join(', '))} | ${entry.commands.map((id) => code(id)).join(', ')} |`)
    }
  } else lines.push('No command takes a fixed list of values.')
  lines.push('')

  lines.push('## Defaults', '')
  if (defaults.length) {
    lines.push('Defaults the engine states in its schemas (other defaults are named in the parameter descriptions).', '')
    lines.push('| Command | Parameter | Default |', '|---|---|---|')
    for (const entry of defaults) lines.push(`| ${code(entry.command)} | ${code(entry.name)} | ${cell(code(JSON.stringify(entry.value)))} |`)
  } else lines.push('No schema states a default; the parameter descriptions name the defaults that exist.')
  lines.push('')

  lines.push('## Commands', '', `${commands.length} commands, by menu.`, '')
  const menus = new Map()
  for (const command of commands) {
    const key = command.menu?.length ? command.menu.join(' > ') : '(no menu)'
    menus.set(key, [...(menus.get(key) ?? []), command])
  }
  for (const [menu, list] of menus) {
    lines.push(`### ${menu}`, '')
    for (const command of list) {
      const kind = command.mutates === false ? 'reads' : 'writes'
      const description = (command.description ?? command.title ?? '').replace(/\s+/g, ' ').trim()
      const params = Object.entries(command.schema ?? {}).filter(([, node]) => node)
      lines.push(`- ${code(command.id)} (${kind}): ${description}${params.length ? '' : ' No parameters.'}`)
      for (const [name, node] of params) lines.push(`  - ${describeParam(name, node)}`)
    }
    lines.push('')
  }

  lines.push('## Examples', '')
  const examples = guideExamples(guide)
  if (examples.length) {
    lines.push('From [`agent/guide.md`](../agent/guide.md).', '')
    for (const example of examples) lines.push(`### ${example.title}`, '', example.body, '')
  } else lines.push('`agent/guide.md` has no examples yet.', '')
  return `${lines.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd()}\n`
}

async function main(argv) {
  const [repo, engineDir, module, cls, flag] = argv
  if (!repo || !engineDir || !module || !cls) {
    console.error('usage: writing-format.mjs <kit repo> <engine dir> <module> <class> [--check]')
    return 2
  }
  const manifest = JSON.parse(readFileSync(path.join(repo, 'kit.json'), 'utf8'))
  const packageManifest = path.join(engineDir, '..', 'kit.json')
  const engineVersion = existsSync(packageManifest) ? JSON.parse(readFileSync(packageManifest, 'utf8')).version : 'build'
  const guidePath = path.join(repo, 'agent', 'guide.md')
  const guide = existsSync(guidePath) ? readFileSync(guidePath, 'utf8') : ''
  const sdk = await import(pathToFileURL(path.resolve(engineDir, `${module}.js`)).href)
  sdk.initSync({ module: readFileSync(path.resolve(engineDir, `${module}_bg.wasm`)) })
  const doc = sdk[cls].create('Untitled', 612, 792)
  const text = writingFormat({ manifest, commands: JSON.parse(doc.commands()), guide, engineVersion })
  const out = path.join(repo, 'docs', 'writing-format.md')
  if (flag === '--check') {
    const same = existsSync(out) && readFileSync(out, 'utf8') === text
    if (!same) console.error(`${out} differs from the engine's catalogue; run tools/writing-format.mjs`)
    return same ? 0 : 1
  }
  writeFileSync(out, text)
  console.log(`wrote ${out} (${text.length} bytes)`)
  return 0
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) process.exitCode = await main(process.argv.slice(2))
