#!/usr/bin/env node
// The Kition family: every public product and the kits by product line, rendered from one source,
// the `family` of templates/community/repositories.json (and its kit entries' title, github and
// description). Everything that introduces the family is rendered here, never copied by hand:
//
//   - the "## The Kition family" section of each repository's README, between kition-family
//     markers before "## License" (tools/sync-community.mjs writes and checks it);
//   - the npm READMEs of the kit packages (tools/kit-npm-package.mjs);
//   - the npm READMEs of this repository's packages (packages/*/README.md): the package's own text,
//     then a generated tail between kition-family markers ("Part of the Kition SDK", the family,
//     the license);
//   - the organization profile, templates/community/org-profile.md (the profile/README.md of a
//     future KitionAI/.github repository).
//
//   node tools/kition-family.mjs [--check]
//
// writes the org profile and the generated tails of packages/*/README.md (a README without a tail
// gets one at its end); with --check it writes nothing, lists each file that is missing or differs,
// and exits 1 when there is any. Every link is absolute: npm shows READMEs away from GitHub.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const DATA = path.join(root, 'templates', 'community', 'repositories.json')
export const ORG_PROFILE = 'templates/community/org-profile.md'
export const FAMILY_TITLE = 'The Kition family'
export const FAMILY_BEGIN =
  '<!-- kition-family:begin (generated by kition-sdk from templates/community/repositories.json, its family; edit the data there, not this text) -->'
export const FAMILY_END = '<!-- kition-family:end -->'
const SDK_GITHUB = 'https://github.com/KitionAI/kition-sdk'
const DEVELOPER = 'https://developer.kition.ai'
const KIT_SUFFIX = ', for people and AI agents'

export const readData = () => JSON.parse(fs.readFileSync(DATA, 'utf8'))

function fail(message) {
  throw new Error(`templates/community/repositories.json: family: ${message}`)
}

const absolute = (url) => typeof url === 'string' && /^https:\/\/[^\s)]+$/.test(url)

/** A kit entry's short line: its description without "Kition <Name>: " and ", for people and AI agents", capitalized. */
export function shortLine(entry) {
  let line = entry.description
  if (line.startsWith(`${entry.title}: `)) line = line.slice(entry.title.length + 2)
  if (line.endsWith(KIT_SUFFIX)) line = line.slice(0, -KIT_SUFFIX.length)
  return line.charAt(0).toUpperCase() + line.slice(1)
}

/** The kit `kit` as the family knows it: { kit, title, name, github, url, description, short, preview }; throws for a kit not in the data. */
export function kitOf(kit, data = readData()) {
  const entry = data.repositories?.[`kition-${kit}`]
  if (!entry || entry.profile !== 'kit') {
    throw new Error(`${JSON.stringify(kit)} is not a kit of templates/community/repositories.json (no kit entry kition-${kit}): add it there before packaging it`)
  }
  return {
    kit,
    title: entry.title,
    name: entry.title.replace(/^Kition /, ''),
    github: entry.github,
    url: `https://github.com/${entry.github}`,
    description: entry.description,
    short: shortLine(entry),
    preview: (data.family?.preview ?? []).includes(kit),
  }
}

/** The family, checked: { tagline, org, products, lines: [{ name, kits: [kitOf(...)] }], kits }. */
export function readFamily(data = readData()) {
  const family = data.family
  if (!family || typeof family !== 'object') fail('missing')
  if (typeof family.tagline !== 'string' || !family.tagline.trim()) fail('tagline is required')
  if (!absolute(family.org)) fail('org must be an https URL')
  if (!Array.isArray(family.products) || family.products.length === 0) fail('products is required')
  const ids = new Set()
  for (const product of family.products) {
    for (const key of ['id', 'name', 'line']) if (typeof product[key] !== 'string' || !product[key].trim()) fail(`a product has no ${key}`)
    if (ids.has(product.id)) fail(`product ${product.id} twice`)
    ids.add(product.id)
    if (!Array.isArray(product.links) || product.links.length === 0) fail(`${product.id} has no links`)
    for (const link of product.links) {
      if (!Array.isArray(link) || link.length !== 2 || !link[0] || !absolute(link[1])) fail(`${product.id}: a link is [label, https URL]`)
    }
  }
  const kits = []
  const lines = (family.lines ?? []).map((line) => {
    if (typeof line.name !== 'string' || !Array.isArray(line.kits) || line.kits.length === 0) fail('a product line is { name, kits }')
    return { name: line.name, kits: line.kits.map((kit) => {
      if (kits.some((known) => known.kit === kit)) fail(`kit ${kit} in two product lines`)
      const info = kitOf(kit, data)
      kits.push(info)
      return info
    }) }
  })
  const listed = new Set(kits.map((info) => info.kit))
  for (const [name, entry] of Object.entries(data.repositories)) {
    if (entry.profile === 'kit' && !listed.has(name.replace(/^kition-/, ''))) fail(`kit entry ${name} is in no product line`)
  }
  for (const kit of family.preview ?? []) if (!listed.has(kit)) fail(`preview kit ${kit} is in no product line`)
  return { tagline: family.tagline, org: family.org, products: family.products, lines, kits }
}

/**
 * The "## The Kition family" section, ending with a newline. `self` names whose README it is:
 * { kit } (that kit is bold, not a link), { product } (that product's row is bold) or nothing.
 */
export function renderFamily(family, self = {}) {
  const bold = (text, on) => (on ? `**${text}**` : text)
  const rows = family.products.map((product) => {
    const links = product.links.map(([label, url]) => `[${label}](${url})`).join(' · ')
    return `| ${bold(product.name, self.product === product.id)} | ${product.line} | ${links} |`
  })
  const kit = (info) => `${info.kit === self.kit ? `**${info.name}**` : `[${info.name}](${info.url})`}${info.preview ? ' (Preview)' : ''}`
  return [
    `## ${FAMILY_TITLE}`,
    '',
    `Kition is the open pro suite for AI: ${family.kits.length} kits, editors that people and AI agents use on the same files, and the products around them ([all repositories](${family.org})).`,
    '',
    '| Product | What it is | Links |',
    '| --- | --- | --- |',
    ...rows,
    '',
    '| Product line | Kits |',
    '| --- | --- |',
    ...family.lines.map((line) => `| ${line.name} | ${line.kits.map(kit).join(' · ')} |`),
    '',
  ].join('\n')
}

/** The family section between kition-family markers, as a README holds it. */
export const familyBlock = (family, self) => `${FAMILY_BEGIN}\n${renderFamily(family, self)}${FAMILY_END}\n`

/** Where the kition-family blocks of `text` are: [{ start, end }] (end after the end marker's line); `broken` when a marker has no partner. */
export function findBlocks(text) {
  const blocks = []
  let broken = false
  let at = 0
  for (;;) {
    const start = text.indexOf('<!-- kition-family:begin', at)
    const nextEnd = text.indexOf(FAMILY_END, at)
    if (start < 0) {
      if (nextEnd >= 0) broken = true
      break
    }
    if (nextEnd >= 0 && nextEnd < start) broken = true
    const end = text.indexOf(FAMILY_END, start)
    if (end < 0) {
      broken = true
      break
    }
    let stop = end + FAMILY_END.length
    if (text[stop] === '\n') stop++
    blocks.push({ start, end: stop })
    at = stop
  }
  return { blocks, broken }
}

/** `text` without its kition-family blocks: the repository's own text. */
export function withoutFamily(text) {
  const { blocks } = findBlocks(text)
  let out = text
  for (const block of [...blocks].reverse()) out = out.slice(0, block.start) + out.slice(block.end)
  return out
}

/** The organization profile (a KitionAI/.github repository's profile/README.md). */
export function renderOrgProfile(family) {
  const sdk = family.products.find((product) => product.id === 'sdk')
  const lineNames = family.lines.map((line) => line.name.toLowerCase())
  const fields = `${lineNames.slice(0, -1).join(', ')} and ${lineNames.at(-1)}`
  const kitRows = family.lines.flatMap((line) =>
    line.kits.map((info, index) => `| ${index === 0 ? line.name : ''} | [${info.name}](${info.url})${info.preview ? ' (Preview)' : ''} | ${info.short} |`),
  )
  return [
    '<!-- Generated by kition-sdk tools/kition-family.mjs from templates/community/repositories.json (family): the profile/README.md of the KitionAI/.github repository. Edit the data, then run node tools/kition-family.mjs. -->',
    `# ${family.tagline}`,
    '',
    `Kition is ${family.kits.length} professional editors, called kits, for ${fields} work, and each kit's one engine serves a person in its editor, an AI agent through its commands, and a program through code. Use the kits in Kition Desktop, put them in your own product with the Kition SDK, or give them to your agent with the \`kition\` command line.`,
    '',
    '## Where to start',
    '',
    '- **Use it:** [kition.ai](https://kition.ai)',
    `- **Build with it:** [developer.kition.ai](${DEVELOPER})`,
    `- **Give it to your agent:** \`npx @kition/cli\` ([the \`kition\` command line](${sdk ? `${SDK_GITHUB}/blob/main/docs/sdk/cli.md` : DEVELOPER}))`,
    '',
    '## Products',
    '',
    '| Product | What it is | Links |',
    '| --- | --- | --- |',
    ...family.products.map((product) => `| ${product.name} | ${product.line} | ${product.links.map(([label, url]) => `[${label}](${url})`).join(' · ')} |`),
    '',
    '## Kits',
    '',
    '| Product line | Kit | What it is |',
    '| --- | --- | --- |',
    ...kitRows,
    '',
  ].join('\n')
}

/** A kit.json's formats as tables write them: { opens, creates, exports }, each `.md`, `.markdown` or a dash. */
export function kitFormats(manifest) {
  const list = (values) => {
    const unique = [...new Set(values.filter((extension) => typeof extension === 'string' && extension))]
    return unique.length > 0 ? unique.map((extension) => `\`.${extension.replace(/^\./, '')}\``).join(', ') : '—'
  }
  const array = (value) => (Array.isArray(value) ? value : [])
  return {
    opens: list(array(manifest?.formats).flatMap((format) => array(format?.extensions))),
    creates: list(array(manifest?.creates).map((create) => create?.extension)),
    exports: list(array(manifest?.exports).map((exported) => exported?.extension)),
  }
}

/** The generated tail of an SDK package's README (packages/<directory>/README.md), markers included. */
export function packageTail(family, manifest, directory) {
  const sdk = family.products.find((product) => product.id === 'sdk')
  const purpose = sdk.line.charAt(0).toLowerCase() + sdk.line.slice(1)
  const self = manifest.name === '@kition/cli' ? { product: 'cli' } : { product: 'sdk' }
  return [
    FAMILY_BEGIN,
    '## Part of the Kition SDK',
    '',
    `\`${manifest.name}\` is a package of the [Kition SDK](${SDK_GITHUB}) ([its source](${SDK_GITHUB}/tree/main/packages/${directory})), which lets you ${purpose}. Guides and reference: [developer.kition.ai](${DEVELOPER}).`,
    '',
    renderFamily(family, self).trimEnd(),
    '',
    '## License',
    '',
    `${manifest.license} ([LICENSE](${SDK_GITHUB}/blob/main/LICENSE)).`,
    FAMILY_END,
    '',
  ].join('\n')
}

/** `readme` with its generated tail replaced by `tail`, or appended after the package's own text. */
export function withTail(readme, tail) {
  const { blocks } = findBlocks(readme)
  const own = (blocks.length > 0 ? readme.slice(0, blocks[0].start) : readme).replace(/\s+$/, '')
  return `${own}\n\n${tail}`
}

/** Every file this tool generates in kition-sdk: [{ path, text }] (relative paths). */
export function generated(data = readData()) {
  const family = readFamily(data)
  const files = [{ path: ORG_PROFILE, text: renderOrgProfile(family) }]
  for (const directory of fs.readdirSync(path.join(root, 'packages')).sort()) {
    const manifestFile = path.join(root, 'packages', directory, 'package.json')
    if (!fs.existsSync(manifestFile)) continue
    const manifest = JSON.parse(fs.readFileSync(manifestFile, 'utf8'))
    if (manifest.private) continue
    const file = `packages/${directory}/README.md`
    const old = fs.existsSync(path.join(root, file)) ? fs.readFileSync(path.join(root, file), 'utf8') : null
    if (old === null) {
      files.push({ path: file, text: null, missing: `the package's own README text (what it is, how to install and use it) is missing` })
      continue
    }
    files.push({ path: file, text: withTail(old, packageTail(family, manifest, directory)) })
  }
  return files
}

function main(argv) {
  const check = argv.includes('--check')
  const unknown = argv.filter((arg) => arg !== '--check')
  if (unknown.length > 0) {
    console.error('usage: kition-family.mjs [--check]')
    process.exit(2)
  }
  let problems = 0
  let unwritable = 0
  for (const file of generated()) {
    const full = path.join(root, file.path)
    if (file.text === null) {
      console.log(`missing: ${file.path} (${file.missing})`)
      problems++
      unwritable++
      continue
    }
    const old = fs.existsSync(full) ? fs.readFileSync(full, 'utf8') : null
    if (old === file.text) continue
    problems++
    if (check) console.log(`${old === null ? 'missing' : 'differs'}: ${file.path}`)
    else {
      fs.writeFileSync(full, file.text)
      console.log(`${old === null ? 'create' : 'update'}: ${file.path}`)
    }
  }
  if (problems === 0) console.log('kition-family: up to date')
  process.exit((check && problems > 0) || unwritable > 0 ? 1 : 0)
}

if (process.argv[1] && fs.realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)) main(process.argv.slice(2))
